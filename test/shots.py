import sys, pathlib
from playwright.sync_api import sync_playwright
root = pathlib.Path(__file__).resolve().parent.parent
out = pathlib.Path(sys.argv[1]); out.mkdir(exist_ok=True)
url = (root / 'renderer' / 'index.html').as_uri()
errors = []
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--allow-file-access-from-files'])
    pg = b.new_page(viewport={'width': 1500, 'height': 920})
    pg.on('pageerror', lambda e: errors.append(str(e)))
    pg.on('console', lambda m: errors.append(m.text) if m.type == 'error' else None)
    pg.goto(url); pg.wait_for_timeout(600)
    pg.screenshot(path=str(out / '1-home.png'))
    pg.click('[data-v=movies]'); pg.wait_for_timeout(300); pg.screenshot(path=str(out / '2-movies.png'))
    pg.click('.card[data-id="mov:tb1"]') if pg.query_selector('.card[data-id="mov:tb1"]') else None
    pg.wait_for_timeout(300); pg.screenshot(path=str(out / '3-movie-detail.png'))
    pg.keyboard.press('Escape')
    pg.click('[data-v=tv]'); pg.wait_for_timeout(200)
    pg.click('.card >> nth=1'); pg.wait_for_timeout(400); pg.screenshot(path=str(out / '4-tv-detail.png'))
    pg.keyboard.press('Escape')
    pg.click('[data-v=games]'); pg.wait_for_timeout(300); pg.screenshot(path=str(out / '5-games.png'))
    pg.click('[data-v=audiobooks]'); pg.wait_for_timeout(200); pg.click('.card >> nth=0'); pg.wait_for_timeout(200)
    pg.click('#pAb'); pg.wait_for_timeout(300); pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    pg.screenshot(path=str(out / '6-audiobooks.png'))
    pg.click('#abClose'); pg.click('[data-v=music]'); pg.wait_for_timeout(300); pg.screenshot(path=str(out / '11-music.png'))
    pg.click('.card[data-cat=music] >> nth=1'); pg.wait_for_timeout(300); pg.click('#pAl'); pg.wait_for_timeout(400); pg.screenshot(path=str(out / '12-album.png'))
    pg.keyboard.press('Escape')
    pg.click('[data-v=setup]'); pg.wait_for_timeout(200); pg.screenshot(path=str(out / '7-setup-general.png'))
    pg.click('[data-tab=music]'); pg.wait_for_timeout(200); pg.screenshot(path=str(out / '8-setup-music.png'), full_page=False)
    pg.click('[data-tab=games]'); pg.wait_for_timeout(200)
    pg.wait_for_timeout(200); pg.evaluate("document.querySelector('#view').scrollTop=900"); pg.wait_for_timeout(200)
    pg.screenshot(path=str(out / '9-setup-games.png'))
    pg.evaluate("document.querySelector('#view').scrollTop=0"); pg.wait_for_timeout(100)
    pg.evaluate("[...document.querySelectorAll('.card2 h3')].find(h => h.textContent.startsWith('Emulation')).scrollIntoView()"); pg.wait_for_timeout(300)
    pg.screenshot(path=str(out / '13-setup-emulation.png'))
    pg.click('[data-v=games]'); pg.wait_for_timeout(500)
    pg.screenshot(path=str(out / '14-games-landing.png'))
    pg.click('[data-col="sys:snes"]'); pg.wait_for_timeout(400)
    pg.screenshot(path=str(out / '14b-games-snes.png'))
    pg.click('.card >> nth=0'); pg.wait_for_timeout(300); pg.evaluate("document.querySelector('#sheet').scrollTop=300"); pg.wait_for_timeout(200)
    pg.screenshot(path=str(out / '15-rom-detail.png')); pg.keyboard.press('Escape')
    pg.fill('#q', 'ma'); pg.wait_for_timeout(400); pg.screenshot(path=str(out / '10-search.png'))
    b.close()
print('errors:', errors)
